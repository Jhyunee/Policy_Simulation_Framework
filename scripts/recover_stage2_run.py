"""Recover artifacts from a stage2-toc run that crashed in the post-scenario
aggregation step (typically `run_phase_stakeholder_synthesizer` hitting a
400 Bad Request when its prompt swelled past the API limit on large cuts).

What gets recovered:
  1. `aggregated_quantitative.json` — deterministic aggregated_final +
     implementation_gap_report (mirrors `aggregate_across_scenarios`).
  2. `run_log.json` — reconstructed from the per-scenario stat lines
     captured in the stdout log file (one per scenario, of the form
     `[Sxx_...] +<tokens> tokens (<calls> calls, <elapsed>s)`).

Nothing is regenerated by LLM — all data is parsed from the disk artifacts
already produced before the crash.

Usage:
    python scripts/recover_stage2_run.py \\
        --run-dir outputs/kor/ssf/stage2_toc/<dir> \\
        --stdout-log /private/tmp/claude-501/.../tasks/<bg_task_id>.output
"""

from __future__ import annotations

import argparse
import json
import re
from datetime import datetime
from pathlib import Path
from statistics import mean
from typing import Any, Optional


# ----------------------------------------------------------------------------- aggregator (same math as stage2_toc.modules.aggregate_across_scenarios)

def _scenario_files(run_dir: Path) -> list[Path]:
    return sorted(run_dir.glob("scenario_*.json"), key=lambda p: int(p.stem.split("_")[1]))


def _impact_fields(schema: dict[str, Any]) -> list[dict[str, Any]]:
    for phase in schema.get("phases") or []:
        if phase.get("phase") == "Impact":
            return [
                f for f in (phase.get("prediction_fields") or [])
                if f.get("type") in ("int", "float")
            ]
    return []


def _aggregated_final(impact_fields, scenarios):
    out: dict[str, Optional[float]] = {}
    for field in impact_fields:
        name = field["name"]
        num = denom = 0.0
        unweighted: list[float] = []
        for s in scenarios:
            v = (s.get("scenario_impact") or {}).get(name)
            w = (s.get("scenario_confidence") or {}).get(name)
            if not isinstance(v, (int, float)):
                continue
            unweighted.append(float(v))
            if isinstance(w, (int, float)) and w > 0:
                num += float(v) * float(w)
                denom += float(w)
        if denom > 0:
            out[name] = num / denom
        elif unweighted:
            out[name] = mean(unweighted)
        else:
            out[name] = None
    return out


def _impl_gap_report(scenarios):
    acc: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for s in scenarios:
        for c in (s.get("cross_checks") or []):
            acc.setdefault((c.get("phase"), c.get("variable")), []).append(c)
    out: list[dict[str, Any]] = []
    for (phase, variable), checks in acc.items():
        def m(attr):
            vals = [c.get(attr) for c in checks if isinstance(c.get(attr), (int, float))]
            return float(sum(vals)) / len(vals) if vals else None
        out.append({
            "phase": phase, "variable": variable,
            "forward_agg": m("forward_agg"), "backward_agg": m("backward_agg"),
            "gap": m("gap"), "relative_gap": m("relative_gap"),
            "consistency": m("consistency"), "aggregated_value": m("aggregated_value"),
        })
    phase_order = ["Inputs", "Activities", "Outputs", "Outcomes", "Impact"]
    out.sort(key=lambda r: (phase_order.index(r["phase"]) if r["phase"] in phase_order else 99, r["variable"]))
    return out


# ----------------------------------------------------------------------------- run_log reconstruction

_STAT_RE = re.compile(
    r"\[(?P<sid>S\d+_[^\]]+)\]\s+\+(?P<tokens>\d+)\s+tokens\s+\((?P<calls>\d+)\s+calls,\s+(?P<elapsed>[\d.]+)s\)"
)


def _parse_scenario_stats(stdout_text: str) -> list[dict[str, Any]]:
    """Pull one log_entry per scenario by matching the stat print line."""
    entries: list[dict[str, Any]] = []
    seen = set()
    for m in _STAT_RE.finditer(stdout_text):
        sid = m.group("sid")
        if sid in seen:
            continue
        seen.add(sid)
        total_tokens = int(m.group("tokens"))
        calls = int(m.group("calls"))
        elapsed = float(m.group("elapsed"))
        # Estimate a rough prompt/completion split when we only have totals.
        # Defaults to attributing everything to prompt_tokens since we cannot
        # recover the split post-hoc; consumers can ignore it.
        entries.append({
            "scenario_id": sid,
            "llm_calls": calls,
            "total_tokens": total_tokens,
            "elapsed_sec": elapsed,
            "prompt_tokens": None,
            "completion_tokens": None,
        })
    return entries


def _parse_start_end(stdout_text: str, fallback_run_dir: Path) -> tuple[str, str]:
    """Best-effort start/end derivation. Without explicit timestamps in stdout
    we just fall back to the run_dir mtime range."""
    # Try parsing leading timestamp from filename: 20260515111201_...
    ts_match = re.match(r"^(\d{14})", fallback_run_dir.name)
    if ts_match:
        start = datetime.strptime(ts_match.group(1), "%Y%m%d%H%M%S").isoformat()
    else:
        start = datetime.fromtimestamp(fallback_run_dir.stat().st_ctime).isoformat()
    # End = mtime of newest scenario_*.json
    paths = list(fallback_run_dir.glob("scenario_*.json"))
    if paths:
        end = datetime.fromtimestamp(max(p.stat().st_mtime for p in paths)).isoformat()
    else:
        end = datetime.now().isoformat()
    return start, end


# ----------------------------------------------------------------------------- main

def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run-dir", type=Path, required=True, help="stage2-toc run dir (contains scenario_*.json + inner_schema.json)")
    p.add_argument("--stdout-log", type=Path, default=None, help="Optional stdout log file to extract per-scenario stats from")
    p.add_argument("--simulation-target", type=str, default=None, help="Simulation target string (recorded in run_log; auto-detected from run_dir name if omitted)")
    p.add_argument("--model", type=str, default=None, help="LLM model name for run_log (defaults to 'deepseek-chat')")
    args = p.parse_args()

    rd: Path = args.run_dir
    if not rd.is_dir():
        raise SystemExit(f"--run-dir not a directory: {rd}")

    # 1. quantitative aggregation
    schema = json.loads((rd / "inner_schema.json").read_text(encoding="utf-8"))
    paths = _scenario_files(rd)
    if not paths:
        raise SystemExit(f"No scenario_*.json files in {rd}")
    scenarios = [json.loads(p.read_text(encoding="utf-8")) for p in paths]
    impact_fields = _impact_fields(schema)
    aggregated_final = _aggregated_final(impact_fields, scenarios)
    impl_gap = _impl_gap_report(scenarios)

    quant_path = rd / "aggregated_quantitative.json"
    quant_path.write_text(json.dumps({
        "run_dir": str(rd),
        "scenario_count": len(scenarios),
        "scenarios_used": [p.stem for p in paths],
        "aggregated_final": aggregated_final,
        "implementation_gap_report": impl_gap,
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {quant_path}")
    print(f"  scenarios: {len(scenarios)}  aggregated_final: {aggregated_final}")

    # 2. run_log reconstruction (best-effort)
    if args.stdout_log and args.stdout_log.exists():
        stdout_text = args.stdout_log.read_text(encoding="utf-8", errors="replace")
        per_scenario = _parse_scenario_stats(stdout_text)
        start_iso, end_iso = _parse_start_end(stdout_text, rd)
        total_tokens = sum(e["total_tokens"] for e in per_scenario)
        total_calls = sum(e["llm_calls"] for e in per_scenario)
        max_elapsed = max((e["elapsed_sec"] for e in per_scenario), default=0.0)
        # Wall-clock estimate: parallel run → ~ max scenario elapsed; sequential → sum.
        wall_time = max_elapsed
        run_log = {
            "model": args.model or "deepseek-chat",
            "simulation_target": args.simulation_target or "",
            "start_time": start_iso,
            "end_time": end_iso,
            "scenarios": per_scenario,
            "total": {
                "total_tokens": total_tokens,
                "call_count": total_calls,
                "wall_time_sec": round(wall_time, 2),
                "wall_time_min": round(wall_time / 60, 1),
            },
            "recovery_note": "Reconstructed post-hoc from stdout per-scenario stat lines. "
                             "Per-scenario prompt/completion token split is unavailable; only "
                             "total_tokens is recoverable. Wall time = max scenario elapsed (parallel mode).",
        }
        run_log_path = rd / "run_log.json"
        run_log_path.write_text(json.dumps(run_log, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"Wrote {run_log_path}")
        print(f"  scenarios parsed: {len(per_scenario)}")
        print(f"  total tokens: {total_tokens:,}  calls: {total_calls:,}  wall time (max parallel): {wall_time:.0f}s")
    else:
        print("Skipping run_log reconstruction (no --stdout-log provided).")


if __name__ == "__main__":
    main()
